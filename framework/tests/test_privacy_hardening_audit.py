# SEC-04: Input Finiteness Validation (Anti-Poisoning)
# ==============================================================================

def test_fedavg_aggregator_rejects_nan_and_inf_poisoning():
    from fedlearn.server.strategy import FedAvgAggregator
    agg = FedAvgAggregator()

    # NaN in tensor
    nan_tensor = OrderedDict(layer=torch.tensor([1.0, float("nan"), 3.0]))
    with pytest.raises(ValueError, match="non-finite|NaN|Inf"):
        agg.aggregate([("client_bad", nan_tensor, 10)])

    # Inf in tensor
    inf_tensor = OrderedDict(layer=torch.tensor([float("inf"), 2.0]))
    with pytest.raises(ValueError, match="non-finite|NaN|Inf"):
        agg.aggregate([("client_bad", inf_tensor, 10)])

    # Clean tensor passes
    clean_val = torch.tensor([1.0, 2.0, 3.0])
    clean_tensor = OrderedDict(layer=clean_val.clone())
    out = agg.aggregate([("client_good", clean_tensor, 10)])
    assert torch.allclose(out["layer"], clean_val)


def test_composed_strategy_drops_non_finite_client():
    init_params = OrderedDict(layer=torch.tensor([0.0, 0.0]))
    strat = ComposedStrategy(init_params, rule="mean", clip_norm=1.0)
    res = [
        ("c1", OrderedDict(layer=torch.tensor([1.0, 1.0])), 10),
        ("c_poison", OrderedDict(layer=torch.tensor([float("nan"), 1.0])), 10),
    ]
    strat.aggregate_fit(1, res)
    assert strat.last_round_stats["dropped"] == ["c_poison"]
    assert strat.last_round_stats["aggregated"] == 1


