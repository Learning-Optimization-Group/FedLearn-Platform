def test_local_dp_generator_isolated_from_global_seed():
    delta = OrderedDict(w=torch.zeros(500))

    # Client sets global seed
    torch.manual_seed(12345)
    out1 = privatize(delta, clip_norm=1.0, noise_multiplier=1.0, generator=None)

    # Client sets same global seed again
    torch.manual_seed(12345)
    out2 = privatize(delta, clip_norm=1.0, noise_multiplier=1.0, generator=None)

    # Isolated generator ensures noise is NOT identical
    assert not torch.equal(out1["w"], out2["w"])


