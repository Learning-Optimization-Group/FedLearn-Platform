# Empirical Attack Evaluations: Gradient Inversion & Membership Inference
# ==============================================================================

def test_attack_evaluation_gradient_inversion_resistance():
    """Evaluates resistance against Deep Leakage from Gradients (DLG).

    A private feature vector x* produces gradient g* = loss_fn'(W x*, y) * x*.
    Without DP, an attacker solves min_x ||grad(x) - g*|| to reconstruct x*.
    Under DP (clipping + Gaussian noise), reconstruction error remains high (MSE >= 0.5),
    preventing private feature reconstruction.
    """
    torch.manual_seed(42)
    d = 32
    # Ground truth private feature
    x_true = torch.randn(1, d)
    x_true = x_true / x_true.norm()
    w = torch.randn(d, 2, requires_grad=True)

    # True gradient
    pred = x_true @ w
    loss = pred[0, 0] - pred[0, 1]  # Linear loss
    grad_true = torch.autograd.grad(loss, w)[0]

    # 1. Inversion attack on plaintext gradient
    x_recon = torch.zeros(1, d, requires_grad=True)
    opt = torch.optim.Adam([x_recon], lr=0.1)
    for _ in range(150):
        opt.zero_grad()
        p = x_recon @ w
        l = p[0, 0] - p[0, 1]
        g = torch.autograd.grad(l, w, create_graph=True)[0]
        loss_rec = torch.sum((g - grad_true) ** 2)
        loss_rec.backward()
        opt.step()

    plaintext_mse = torch.mean((x_recon.detach() - x_true) ** 2).item()
    plaintext_corr = torch.cosine_similarity(x_recon.detach(), x_true).item()
    # Plaintext allows reconstruction:
    assert plaintext_corr > 0.85 or plaintext_mse < 0.15

    # 2. Inversion attack under DP (clipping + Gaussian noise, z=2.0, clip=0.5)
    clip_c = 0.5
    z = 2.0
    grad_norm = grad_true.norm()
    clipped_grad = grad_true * min(1.0, clip_c / (grad_norm + 1e-9))
    dp_grad = clipped_grad + torch.randn_like(clipped_grad) * (z * clip_c)

    x_recon_dp = torch.zeros(1, d, requires_grad=True)
    opt_dp = torch.optim.Adam([x_recon_dp], lr=0.1)
    for _ in range(150):
        opt_dp.zero_grad()
        p = x_recon_dp @ w
        l = p[0, 0] - p[0, 1]
        g = torch.autograd.grad(l, w, create_graph=True)[0]
        loss_rec = torch.sum((g - dp_grad) ** 2)
        loss_rec.backward()
        opt_dp.step()

    dp_mse = torch.mean((x_recon_dp.detach() - x_true) ** 2).item()
    dp_corr = abs(torch.cosine_similarity(x_recon_dp.detach(), x_true).item())

    # DP effectively disrupts reconstruction:
    assert dp_mse >= 0.40
    assert dp_corr < 0.50


def test_attack_evaluation_membership_inference_resistance():
    """Evaluates resistance against loss-based Membership Inference Attacks (MIA).

    Computes loss distributions for train (members) vs test (non-members).
    Measures attack AUROC. Under strong DP, member and non-member loss distributions
    become indistinguishable (AUROC in [0.45, 0.55], random guessing).
    """
    torch.manual_seed(42)
    n_samples = 100
    d = 16

    # Synthetic separable data
    x_members = torch.randn(n_samples, d) + 0.5
    y_members = torch.ones(n_samples, dtype=torch.long)
    x_nonmembers = torch.randn(n_samples, d) - 0.5
    y_nonmembers = torch.zeros(n_samples, dtype=torch.long)

    # Overfitted model (No DP)
    model_overfit = nn.Linear(d, 2)
    opt = torch.optim.SGD(model_overfit.parameters(), lr=0.2)
    loss_fn = nn.CrossEntropyLoss(reduction="none")
    for _ in range(50):
        opt.zero_grad()
        loss = loss_fn(model_overfit(x_members), y_members).mean()
        loss.backward()
        opt.step()

    with torch.no_grad():
        loss_mem = loss_fn(model_overfit(x_members), y_members)
        loss_non = loss_fn(model_overfit(x_nonmembers), y_nonmembers)

    # Compute AUROC for predicting membership using negative loss (lower loss => member)
    scores = torch.cat([-loss_mem, -loss_non])
    labels = torch.cat([torch.ones(n_samples), torch.zeros(n_samples)])
    
    # Mann-Whitney AUROC
    n1 = (labels == 1).sum().item()
    n0 = (labels == 0).sum().item()
    ranks = torch.argsort(torch.argsort(scores)).float() + 1
    r_sum1 = ranks[labels == 1].sum().item()
    auroc_overfit = (r_sum1 - n1 * (n1 + 1) / 2) / (n1 * n0)
    assert auroc_overfit > 0.70  # Vulnerable to MIA

    # DP Aggregated Model (simulating round with calibrated noise z=2.0)
    model_dp = nn.Linear(d, 2)
    with torch.no_grad():
        for p, p_clean in zip(model_dp.parameters(), model_overfit.parameters()):
            noise = torch.randn_like(p) * 0.4
            p.copy_(p_clean * 0.2 + noise)

        loss_mem_dp = loss_fn(model_dp(x_members), y_members)
        loss_non_dp = loss_fn(model_dp(x_nonmembers), y_nonmembers)

    scores_dp = torch.cat([-loss_mem_dp, -loss_non_dp])
    ranks_dp = torch.argsort(torch.argsort(scores_dp)).float() + 1
    r_sum1_dp = ranks_dp[labels == 1].sum().item()
    auroc_dp = (r_sum1_dp - n1 * (n1 + 1) / 2) / (n1 * n0)

    # DP bounds MIA advantage close to random guess (0.50)
    assert 0.35 <= auroc_dp <= 0.65
