def test_composed_strategy_default_seed_is_random_entropy():
    init_params = OrderedDict(w=torch.zeros(1000))
    s1 = ComposedStrategy(init_params, central_noise_multiplier=1.0, clip_norm=1.0, noise_seed=None)
    s2 = ComposedStrategy(init_params, central_noise_multiplier=1.0, clip_norm=1.0, noise_seed=None)

    # Initial seed states should not be equal
    assert s1._generator.initial_seed() != s2._generator.initial_seed()

    # Noise tensors generated by both must not be identical
    client_update = OrderedDict(w=torch.ones(1000))
    results = [("c1", client_update, 10)]
    out1, _ = s1._pipeline(1, results, apply_noise=True)
    out2, _ = s2._pipeline(1, results, apply_noise=True)
    assert not torch.allclose(out1["w"], out2["w"])


def test_composed_strategy_explicit_seed_is_reproducible_for_testing():
    init_params = OrderedDict(w=torch.zeros(100))
    s1 = ComposedStrategy(init_params, central_noise_multiplier=1.0, clip_norm=1.0, noise_seed=42)
    s2 = ComposedStrategy(init_params, central_noise_multiplier=1.0, clip_norm=1.0, noise_seed=42)

    client_update = OrderedDict(w=torch.ones(100))
    results = [("c1", client_update, 10)]
    out1, _ = s1._pipeline(1, results, apply_noise=True)
    out2, _ = s2._pipeline(1, results, apply_noise=True)
    assert torch.equal(out1["w"], out2["w"])


def test_composed_strategy_suppresses_raw_norms_when_dp_active():
    init_params = OrderedDict(w=torch.zeros(10))
    # DP Active (z = 1.0)
    s_dp = ComposedStrategy(init_params, central_noise_multiplier=1.0, clip_norm=1.0)
    results = [("client_alice", OrderedDict(w=torch.tensor([2.0] * 10)), 10)]
    _, stats_dp = s_dp._pipeline(1, results, apply_noise=True)
    assert stats_dp["orig_norms"] is None, "Raw norms leaked when DP is enabled"

    # DP Inactive (z = 0.0)
    s_nodp = ComposedStrategy(init_params, central_noise_multiplier=0.0, clip_norm=1.0)
    _, stats_nodp = s_nodp._pipeline(1, results, apply_noise=False)
    assert stats_nodp["orig_norms"] is not None
    assert "client_alice" in stats_nodp["orig_norms"]


