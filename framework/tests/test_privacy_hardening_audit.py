"""Security & Privacy audit regression tests and attack evaluations.

Verifies fixes for:
- SEC-01: SecAgg methods authentication and cross-run replay prevention.
- SEC-02: ComposedStrategy noise generator entropy (no deterministic seed=0 default).
- SEC-03: Prevention of unclipped raw update norm leakage in round telemetry.
- SEC-04: Strict non-finite (NaN / Inf) input validation in normalize_update.
- SEC-05: Isolated RNG in local_dp.privatize (no process-global seed hijacking).
- Empirical attack evaluations:
    - Deep Leakage / Gradient Inversion resistance under DP-clipping + noise.
    - Membership Inference Attack (MIA) resistance.
"""
from collections import OrderedDict
import base64
import math
import time

import grpc
import jwt as pyjwt
import pytest
import torch
import torch.nn as nn

from fedlearn.privacy.local_dp import privatize
from fedlearn.security.identity import partition_from_metadata
from fedlearn.security.interceptor import (
    METADATA_KEY,
    PROTECTED_METHODS,
    ConnectionTokenInterceptor,
)
from fedlearn.security.token_verify import DEFAULT_AUDIENCE
from fedlearn.server._update_normalize import normalize_update, normalize_updates
from fedlearn.server.composed_strategy import ComposedStrategy

_SECRET = b"fedlearn-privacy-audit-test-secret-key-32b!"
_SECRET_B64 = base64.b64encode(_SECRET).decode()


def _mint(**overrides):
    payload = {"aud": DEFAULT_AUDIENCE, "exp": int(time.time()) + 300}
    payload.update(overrides)
    return pyjwt.encode(payload, _SECRET, algorithm="HS256")


def _md(token=None):
    return [(METADATA_KEY, token)] if token is not None else []


# ==============================================================================
# SEC-01: SecAgg Authentication & Replay Prevention
# ==============================================================================

def test_secagg_methods_are_in_protected_methods():
    secagg_rpcs = {"PublishPublicKey", "SubmitSecureShares", "SubmitAggregatedShare"}
    assert secagg_rpcs.issubset(PROTECTED_METHODS), (
        f"Missing SecAgg RPCs in PROTECTED_METHODS: {secagg_rpcs - PROTECTED_METHODS}"
    )


def test_secagg_methods_require_token_and_reject_unauthenticated():
    interceptor = ConnectionTokenInterceptor(_SECRET_B64)
    for method in ("PublishPublicKey", "SubmitSecureShares", "SubmitAggregatedShare"):
        denial = interceptor.deny_reason(method, _md(None))
        assert denial is not None, f"Method {method} was allowed without token"
        code, msg = denial
        assert code == grpc.StatusCode.UNAUTHENTICATED
        assert "missing" in msg.lower()


def test_secagg_methods_reject_token_from_different_run():
    interceptor = ConnectionTokenInterceptor(_SECRET_B64, expected_run_id="run-federation-alpha")
    token_wrong_run = _mint(partitionId=7, runId="run-federation-beta")
    for method in ("PublishPublicKey", "SubmitSecureShares", "SubmitAggregatedShare"):
        denial = interceptor.deny_reason(method, _md(token_wrong_run))
        assert denial is not None
        code, msg = denial
        assert code == grpc.StatusCode.PERMISSION_DENIED
        assert "run" in msg.lower()


def test_partition_from_metadata_enforces_expected_run_id():
    token = _mint(partitionId=42, runId="run-101")
    # Correct run matches
    assert partition_from_metadata(_md(token), _SECRET_B64, expected_run_id="run-101") == 42
    # Wrong run rejected
    assert partition_from_metadata(_md(token), _SECRET_B64, expected_run_id="run-202") is None
    # None expected allows any valid token
    assert partition_from_metadata(_md(token), _SECRET_B64, expected_run_id=None) == 42


